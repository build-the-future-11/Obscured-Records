import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { readDraft, validateDraft, wordCount } from "./editorial-content.mjs";

const draftsDirectory = path.resolve("content/drafts");
const articlesDirectory = path.resolve("content/articles");
const outputFile = path.resolve("lib/editorial-drafts.generated.ts");
const loaderFile = path.resolve("lib/editorial-draft-loader.generated.ts");
const dataDirectory = path.resolve("lib/editorial-draft-data.generated");
const lockFile = `${dataDirectory}.lock`;
const shardCount = 64;
const publishedSlugs = new Set(
  fs
    .readdirSync(articlesDirectory)
    .filter((file) => file.endsWith(".mdx"))
    .map((file) => file.replace(/\.mdx$/, "")),
);

const files = fs
  .readdirSync(draftsDirectory)
  .filter((file) => file.endsWith(".md"))
  .sort();
function projectDraft(file) {
    const { metadata, body } = readDraft(path.join(draftsDirectory, file));
    validateDraft(metadata, body);
    return {
      slug: metadata.slug,
      title: metadata.title,
      dek: metadata.dek,
      author: metadata.author,
      createdAt: metadata.createdAt,
      status: metadata.status,
      section: metadata.section,
      tags: metadata.tags,
      description: metadata.description,
      socialPreview: metadata.socialPreview,
      readingTime: metadata.readingTime,
      genre: metadata.genre ?? "Editorial draft",
      sources: metadata.sources,
      reviewChecklist: metadata.reviewChecklist,
      completedChecks: metadata.completedChecks ?? [],
      approvedBy: metadata.approvedBy ?? null,
      approvedAt: metadata.approvedAt ?? null,
      history: metadata.history ?? [],
      words: wordCount(body),
      publishedInArchive: publishedSlugs.has(metadata.slug),
      body,
    };
}

// Stage a complete generation before replacing any previously valid projection.
// Full manuscripts are loaded only by the authorized detail route, one shard at a time.
const staging = `${dataDirectory}.tmp-${process.pid}`;
const header = "// Generated by scripts/generate-editorial-drafts.mjs. Do not edit by hand.\n";
const summaries = [];
const locations = {};
const seen = new Set();
const installed = [];
let retainStaging = false;
let stagingCreated = false;
let failure;
let indexBytes = 0;
let lockIdentity;
let lock;
try {
  lock = fs.openSync(lockFile, "wx");
} catch (error) {
  if (error.code === "EEXIST") throw new Error(`Editorial generation is locked: ${lockFile}. If a prior process stopped, confirm it is no longer running before removing its lock.`, { cause: error });
  throw error;
}

function fingerprint(file) {
  const identity = fs.lstatSync(file, { throwIfNoEntry: false });
  if (!identity) return undefined;
  if (!identity.isFile()) throw new Error(`Projection destination is not a regular file: ${file}`);
  return { dev: identity.dev, ino: identity.ino, hash: createHash("sha256").update(fs.readFileSync(file)).digest("hex") };
}

function matches(file, expected) {
  const current = fingerprint(file);
  if (!current || !expected) return current === expected;
  return current.dev === expected.dev && current.ino === expected.ino && current.hash === expected.hash;
}

function recordFailure(error) {
  failure = failure ? new AggregateError([failure, error], "Editorial generation failed; additional cleanup errors occurred") : error;
}

try {
  lockIdentity = fs.fstatSync(lock);
  fs.writeFileSync(lock, JSON.stringify({ pid: process.pid, staging }) + "\n");
  fs.mkdirSync(staging);
  stagingCreated = true;
  for (let shard = 0; shard < shardCount; shard++) {
    fs.writeFileSync(path.join(staging, `${shard}.ts`), header + 'import type { EditorialDraft } from "../editorial-types";\nexport const drafts: EditorialDraft[] = [\n');
  }
  for (let index = 0; index < files.length; index++) {
    const draft = projectDraft(files[index]);
    if (files[index] !== `${draft.slug}.md` || seen.has(draft.slug)) throw new Error(`Duplicate or mismatched slug: ${draft.slug}`);
    seen.add(draft.slug);
    const shard = index % shardCount;
    fs.appendFileSync(path.join(staging, `${shard}.ts`), JSON.stringify(draft) + ",\n");
    locations[draft.slug] = shard;
    summaries.push({
      slug: draft.slug, title: draft.title, dek: draft.dek, section: draft.section,
      status: draft.status, tags: draft.tags, words: draft.words,
      publishedInArchive: draft.publishedInArchive, sourceCount: draft.sources.length,
      verifiedSources: draft.sources.filter(source => source.status === "verified").length,
      totalChecks: draft.reviewChecklist.length,
      completedChecks: draft.reviewChecklist.filter(check => draft.completedChecks.includes(check)).length,
      approvedBy: draft.status === "approved" ? draft.approvedBy : null,
      kind: draft.genre.includes("reporting plan") ? "reporting-plan" : "manuscript",
    });
  }
  for (let shard = 0; shard < shardCount; shard++) fs.appendFileSync(path.join(staging, `${shard}.ts`), "];\n");
  let loader = header + 'import type { EditorialDraft } from "./editorial-types";\n';
  loader += `const locations: Record<string, number> = ${JSON.stringify(locations)};\n`;
  loader += "export async function loadEditorialDraft(slug: string): Promise<EditorialDraft | undefined> {\n";
  loader += "  if (!Object.hasOwn(locations, slug)) return undefined;\n  switch (locations[slug]) {\n";
  for (let shard = 0; shard < shardCount; shard++) {
    loader += `    case ${shard}: return (await import("./editorial-draft-data.generated/${shard}.ts")).drafts.find(draft => draft.slug === slug);\n`;
  }
  loader += "  }\n}\n";
  const indexSource = header + 'import type { EditorialQueueItem } from "./editorial-queue";\n' +
    `export const editorialQueue: EditorialQueueItem[] = ${JSON.stringify(summaries)};\n`;
  indexBytes = Buffer.byteLength(indexSource);
  const stagedIndex = path.join(staging, "editorial-drafts.generated.ts");
  const stagedLoader = path.join(staging, "editorial-draft-loader.generated.ts");
  fs.writeFileSync(stagedIndex, indexSource);
  fs.writeFileSync(stagedLoader, loader);
  fs.mkdirSync(dataDirectory, { recursive: true });
  const backupDirectory = path.join(staging, "backups");
  fs.mkdirSync(backupDirectory);
  const replacements = [
    ...Array.from({ length: shardCount }, (_, shard) => ({ staged: path.join(staging, `${shard}.ts`), destination: path.join(dataDirectory, `${shard}.ts`) })),
    { staged: stagedLoader, destination: loaderFile },
    { staged: stagedIndex, destination: outputFile },
  ];
  // Prepare every backup before replacing anything. The lock serializes
  // generators; identity/content checks also preserve intervening editor changes.
  for (const replacement of replacements) {
    replacement.previous = fingerprint(replacement.destination);
    replacement.next = fingerprint(replacement.staged);
    if (replacement.previous) {
      replacement.backup = path.join(backupDirectory, path.basename(replacement.destination));
      fs.copyFileSync(replacement.destination, replacement.backup, fs.constants.COPYFILE_EXCL);
      if (fingerprint(replacement.backup).hash !== replacement.previous.hash) throw new Error(`Projection changed while backing up: ${replacement.destination}`);
    }
  }
  for (const replacement of replacements) {
    if (!matches(replacement.destination, replacement.previous)) throw new Error(`Projection changed before installation: ${replacement.destination}`);
    fs.renameSync(replacement.staged, replacement.destination);
    installed.push(replacement);
  }
} catch (error) {
  const rollbackErrors = [];
  for (const replacement of installed.reverse()) {
    try {
      if (!matches(replacement.destination, replacement.next)) throw new Error(`Preserved concurrently changed projection: ${replacement.destination}`);
      if (replacement.backup) fs.renameSync(replacement.backup, replacement.destination);
      else fs.unlinkSync(replacement.destination);
    } catch (rollbackError) {
      rollbackErrors.push(rollbackError);
    }
  }
  retainStaging = rollbackErrors.length > 0;
  failure = retainStaging
    ? new AggregateError([error, ...rollbackErrors], `Editorial generation failed; rollback needs manual review. Recovery files retained at ${staging}`)
    : error;
} finally {
  try { if (stagingCreated && !retainStaging) fs.rmSync(staging, { recursive: true, force: true }); }
  catch (error) { recordFailure(error); }
  try { fs.closeSync(lock); }
  catch (error) { recordFailure(error); }
  try {
    const current = fs.lstatSync(lockFile, { throwIfNoEntry: false });
    if (current && lockIdentity && current.dev === lockIdentity.dev && current.ino === lockIdentity.ino) fs.unlinkSync(lockFile);
    else if (current) throw new Error(`Preserved changed generation lock: ${lockFile}`);
  } catch (error) { recordFailure(error); }
}
if (failure) throw failure;
console.log(`Generated ${files.length} private summaries and ${shardCount} lazy manuscript shards (${indexBytes} index bytes).`);
