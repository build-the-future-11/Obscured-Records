import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";

// Deliberate allowlist: additions need review, rather than embedding arbitrary
// files discovered in public/. Existing source bytes are never modified.
const filenames = [
  "apollo-1-illustration-480.webp", "apollo-1-illustration-960.webp", "apollo-1-illustration.webp",
  "fedex-705-480.webp", "fedex-705-960.webp", "fedex-705.webp",
  "goiania-source-480.webp", "goiania-source-960.webp", "goiania-source.webp",
  "ixtoc-1-illustration-480.webp", "ixtoc-1-illustration-960.webp", "ixtoc-1-illustration.webp",
  "lake-nyos-480.webp", "lake-nyos.webp",
  "therac-25-480.webp", "therac-25.webp",
  "triangle-factory-illustration-480.webp", "triangle-factory-illustration-960.webp", "triangle-factory-illustration.webp",
  "wirecard-480.webp", "wirecard-960.webp", "wirecard.webp",
];
const publicDirectory = path.resolve("public");
const output = path.resolve("lib/reader-images.generated.ts");
const entries = [];
let totalBytes = 0;
for (const filename of filenames) {
  const file = path.join(publicDirectory, filename);
  if (!fs.lstatSync(file).isFile()) throw new Error(`Reader image must be a regular file: ${filename}`);
  const bytes = fs.readFileSync(file);
  if (bytes.length < 12 || bytes.toString("ascii", 0, 4) !== "RIFF" || bytes.toString("ascii", 8, 12) !== "WEBP") throw new Error(`Reader image is not a WebP file: ${filename}`);
  totalBytes += bytes.length;
  entries.push([filename, { sha256: createHash("sha256").update(bytes).digest("hex"), byteLength: bytes.length, base64: bytes.toString("base64") }]);
}
const source = '// Generated by scripts/generate-reader-images.mjs. Exact source bytes; do not edit by hand.\n' +
  'export type ReaderImage = { readonly sha256: string; readonly byteLength: number; readonly base64: string };\n' +
  `export const readerImages: Readonly<Record<string, ReaderImage>> = Object.freeze(${JSON.stringify(Object.fromEntries(entries), null, 2)});\n`;
const temporary = `${output}.tmp-${process.pid}`;
let staged = false;
try {
  fs.writeFileSync(temporary, source, { flag: "wx" }); staged = true;
  fs.renameSync(temporary, output); staged = false;
} finally { if (staged) fs.unlinkSync(temporary); }
console.log(`Generated ${entries.length} exact reader images (${totalBytes} source bytes, ${Buffer.byteLength(source)} module bytes).`);
