import fs from "node:fs";
import path from "node:path";
import { readDraft, validateDraft, wordCount } from "./editorial-content.mjs";

const draftsDirectory = path.resolve("content/drafts");
const articlesDirectory = path.resolve("content/articles");
const outputFile = path.resolve("lib/editorial-drafts.generated.ts");
const publishedSlugs = new Set(
  fs
    .readdirSync(articlesDirectory)
    .filter((file) => file.endsWith(".mdx"))
    .map((file) => file.replace(/\.mdx$/, "")),
);

const drafts = fs
  .readdirSync(draftsDirectory)
  .filter((file) => file.endsWith(".md"))
  .sort()
  .map((file) => {
    const { metadata, body } = readDraft(path.join(draftsDirectory, file));
    validateDraft(metadata, body);
    return {
      slug: metadata.slug,
      title: metadata.title,
      dek: metadata.dek,
      author: metadata.author,
      createdAt: metadata.createdAt,
      status: metadata.status,
      section: metadata.section,
      tags: metadata.tags,
      description: metadata.description,
      socialPreview: metadata.socialPreview,
      readingTime: metadata.readingTime,
      genre: metadata.genre ?? "Editorial draft",
      sources: metadata.sources,
      reviewChecklist: metadata.reviewChecklist,
      completedChecks: metadata.completedChecks ?? [],
      approvedBy: metadata.approvedBy ?? null,
      approvedAt: metadata.approvedAt ?? null,
      history: metadata.history ?? [],
      words: wordCount(body),
      publishedInArchive: publishedSlugs.has(metadata.slug),
      body,
    };
  });

const source = `// Generated by scripts/generate-editorial-drafts.mjs. Do not edit by hand.\n` +
  `export type EditorialDraft = {\n` +
  `  slug: string; title: string; dek: string; author: string; createdAt: string;\n` +
  `  status: \"draft\" | \"review\" | \"approved\" | \"held\"; section: string;\n` +
  `  tags: string[]; description: string; socialPreview: string; readingTime: string; genre: string;\n` +
  `  sources: Array<{ title: string; url: string; status: string; checkedAt?: string; supports: string }>;\n` +
  `  reviewChecklist: string[]; completedChecks: string[]; approvedBy: string | null; approvedAt: string | null;\n` +
  `  history: Array<{ from: string; to: string; at: string; reason?: string }>; words: number; publishedInArchive: boolean; body: string;\n` +
  `};\n` +
  `export const editorialDrafts: EditorialDraft[] = ${JSON.stringify(drafts, null, 2)};\n`;

fs.writeFileSync(outputFile, source);
console.log(`Generated ${drafts.length} private editorial drafts.`);
